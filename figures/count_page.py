"""Protocol count page of the documentation (Markdown), generated from the `count` job of the newest test run.

What it does:
  Reads runs.json and the artifact `count` (count.json of flex/count.py) of the newest completed test run that
  figures/runs.py downloaded, and writes the page that presents the count: the rule in short, the strict count as the
  headline, the ladder of evidence levels, the families, the device interfaces, the tiers and a check that a reader
  can do in five minutes. Every number comes from count.json; none is typed. Rows of an older count.json that lack the
  family, device-interface or sigrok fields take them from flex/protocols.csv of this commit, and the page says so.
  A test run without a count artifact gives a page that says so.

Usage: python figures/count_page.py <runs folder> <out count.md>
"""

import csv
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TIERS = [
    ("isa-basis", "the instruction set was designed from these programs"),
    ("after-isa", "written by the design team after the instruction set was fixed"),
    ("hold-out", "chosen by a stated rule after the instruction set was fixed, written from public documents"),
    ("helper", "protocols that have a line helper designed for them in the RTL"),
    ("P before tag", "the candidate list of the counting rule (section 7), written before the `rtl-freeze` tag"),
    ("P after tag", "the candidate list, written after the `rtl-freeze` tag"),
    ("blind", "the blind arm, by a writer who did not see the firmware"),
    ("census", "the census of the pre-registration"),
]
AFTER_TAG = {"P after tag", "blind", "census"}


def link(run):
    return f"[run {run['id']}]({run['url']})" if run else "no run"


def notes_of(C, path):
    """The notes of the count (the runs it read): from count.json, or from the list at the top of count.md."""
    if C.get("notes") is not None:
        return C["notes"]
    md = os.path.join(os.path.dirname(path), "count.md")
    out = []
    if os.path.exists(md):
        for line in open(md, encoding="utf-8").read().splitlines()[1:]:
            if line.startswith("- "):
                out.append(line[2:])
            elif line.startswith("**"):
                break
    return out


def main(runs_dir, out_md):
    with open(os.path.join(runs_dir, "runs.json"), encoding="utf-8") as f:
        R = json.load(f)
    repo, branch = R["repo"], R["branch"]
    test = R["runs"].get("test")
    hits = []
    if test and test["artifacts"].get("count"):
        hits = sorted(glob.glob(os.path.join(test["artifacts"]["count"], "**", "count.json"), recursive=True))
    L = ["# Protocol count\n"]
    intro = (f"This page is generated by the docs workflow ([figures/count_page.py](https://github.com/{repo}/blob/"
             f"{branch}/figures/count_page.py)) from the artifact `count` of the newest completed test run on branch "
             f"`{branch}`")
    if not hits:
        L.append(intro + f": {link(test)} has no count artifact, so this build shows no count. The rule is on the "
                 "[Counting rule](counting.md) page.\n")
        with open(out_md, "w", encoding="utf-8") as f:
            f.write("\n".join(L))
        print(f"no count artifact in {link(test)}")
        return
    path = hits[0]
    with open(path, encoding="utf-8") as f:
        C = json.load(f)
    rows = C["rows"]
    filled = [r for r in rows if "family" not in r]
    if filled:
        with open(os.path.join(ROOT, "flex", "protocols.csv"), newline="", encoding="utf-8") as f:
            reg = {r["program"]: r for r in csv.DictReader(f)}
        for r in rows:
            for k in ("family", "device_interface", "sigrok"):
                r.setdefault(k, reg.get(r["program"], {}).get(k, ""))
    protos = {}
    for r in rows:
        if r["class"] == "protocol":
            protos.setdefault(r["protocol"], []).append(r)
    strict, broad = C["strict"], C["broad"]
    ab = sorted(p for p, rs in protos.items() if any(r["a"] and r["b"] for r in rs))
    n = len(strict)

    L.append(intro + f": {link(test)} (commit [`{test['sha'][:7]}`](https://github.com/{repo}/commit/{test['sha']}), "
             f"started {test['created'].replace('T', ' ').replace('Z', ' UTC')}). The count itself is computed by "
             f"[flex/count.py](https://github.com/{repo}/blob/{branch}/flex/count.py) from the registry "
             f"[flex/protocols.csv](https://github.com/{repo}/blob/{branch}/flex/protocols.csv), the assembler and "
             "the test results of the runs named below; no number on this page is typed by hand. The rule is fixed on "
             "the [Counting rule](counting.md) page.\n")
    if filled:
        L.append(f"Note: the count.json of this run has no family, device-interface or sigrok fields; for "
                 f"{len(filled)} rows they are taken from flex/protocols.csv of the site commit "
                 f"`{R.get('site_commit', '')[:7]}`.\n")

    L.append("## The count\n")
    L.append(f"**{n} protocols are in the strict count** ({C['programs_strict']} programs): " + ", ".join(strict) + ".\n")
    L.append("A protocol is in the strict count when one of its programs meets four conditions: (a) the firmware "
             "assembles and fits the 512-word program memory alone; (b) in its test the other device is a model "
             "written from a named public document (its issue, address and SHA-256 are in the registry) that uses "
             "nothing of the firmware, the assembler or the reference model; (c) the test passes on the RTL at the "
             "declared clock of 60 MHz; (d) the same test passes on the gate-level netlist of the layout. A protocol "
             "is the link protocol of one specification: its roles, rates and frame options count once; functions, "
             "outline programs, combinations, signal formats and layered message formats are not counted.\n")
    L.append(f"The broad count, which does not need (d), is {len(broad)}. Not counted: "
             f"{len(C['functions'])} function ({', '.join(C['functions']) or 'none'}), {len(C['examples'])} outline "
             f"programs, {len(C['layered'])} layered.\n")

    L.append("## The ladder\n")
    L.append("Each level adds one kind of evidence to the level above it.\n")
    L.append("| Level | What it adds | Protocols |")
    L.append("|---|---|---|")
    L.append(f"| Registry | a firmware program in `fw/` with its row ({len(rows)} programs) | {len(protos)} |")
    L.append(f"| Model from a public document | (a) fits the memory, (b) the other device is a model written from a "
             f"named public document | {len(ab)} |")
    L.append(f"| Broad | (c) the test passes on the RTL at 60 MHz | {len(broad)} |")
    L.append(f"| Strict | (d) the same test passes on the gate-level netlist of the layout | {n} |")
    L.append(f"| Outside decoder | a sigrok decoder is declared for the program's pins on the RTL (run by the docs "
             f"workflow; an oracle separate from the model) | {len(C['sigrok_declared'])} |")
    L.append("")
    L.append("Two levels above these are given per rate, not per protocol: simulation of the layout netlist with the "
             "cell and macro delays of its SDF file at three corners, and measurement on hardware. Both are on the "
             "[Protocols](protocols.md) page, section Rates; no protocol has a hardware measurement, because there "
             "is no silicon yet.\n")

    L.append("## Families\n")
    fam = {}
    for p in strict:
        for f_ in sorted({r["family"] for r in protos[p] if r["strict"]}):
            fam.setdefault(f_ or "(none given)", []).append(p)
    L.append(f"The family is the line code and framing class of a program, so that a reader can see how many kinds of "
             f"link the count holds: the {n} strict protocols are in {len(fam)} families.\n")
    L.append("| Family | Strict protocols | Number |")
    L.append("|---|---|---|")
    for f_, ps in sorted(fam.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        L.append(f"| {f_} | {', '.join(ps)} | {len(ps)} |")
    L.append("")

    L.append("## Device interfaces\n")
    di = C["device_interface_strict"]
    L.append(f"A device interface is an interface that only one kind of device uses (for example one sensor's own "
             f"single-wire link); the registry marks it so that a reader can leave it out. {len(di)} of the {n} strict "
             f"protocols are device interfaces" + (f" ({', '.join(di)})" if di else "") +
             f"; without them the strict count is {n - len(di)}.\n")

    L.append("## Tiers\n")
    order = [t for t, _ in TIERS]
    first = {}
    for p in strict:
        tiers = [r["tier"] for r in protos[p] if r["strict"]]
        first[p] = min(tiers, key=lambda t: order.index(t) if t in order else len(order))
    L.append("The tier says when and how a program was written. A protocol with programs in several tiers is listed "
             "under the earliest tier of its strict programs.\n")
    L.append("| Tier | Meaning | Strict protocols | Number |")
    L.append("|---|---|---|---|")
    extra = sorted({t for t in first.values() if t not in order})
    for t, meaning in TIERS + [(t, "") for t in extra]:
        ps = sorted(p for p, ft in first.items() if ft == t)
        L.append(f"| `{t}` | {meaning} | {', '.join(ps) or '-'} | {len(ps)} |")
    L.append("")
    after = sorted(p for p in strict if any(r["strict"] and r["tier"] in AFTER_TAG for r in protos[p]))
    L.append(f"Only programs written after the `rtl-freeze` tag show what the frozen chip can do for protocols that it "
             f"was not designed for; in this count {len(after)} strict protocols have such a program"
             + (f" ({', '.join(after)})" if after else "") + ". Every other program was written while the RTL could "
             "still change.\n")
    multi = sorted((p, len(rs)) for p, rs in protos.items() if len(rs) > 1)
    if multi:
        L.append("Protocols with more than one program (roles or variants, counted once): "
                 + ", ".join(f"{p} {k}" for p, k in multi) + ".\n")

    L.append("## Check it in five minutes\n")
    L.append(f"1. Open {link(test)} of the test workflow (no sign-in needed). In its annotations, `protocol count` "
             "gives the count line and `protocol count table` the table of conditions (a) to (d) for every program; "
             "they are the numbers of this page.")
    nts = notes_of(C, path)
    L.append("2. The count names the runs it read: " + ("; ".join(nts) if nts else "(no notes in this artifact)") +
             ". A gl_fw run gives the gds run of its netlist and the netlist's SHA-256.")
    L.append("3. Choose one row of the table. Its test names are in the registry (columns `rtl_tests`, `gl_tests`); "
             "find them in `results.xml` of the artifact `test-results` of the test run, and of the artifact "
             "`gl_protocols_*` or `gl_fw_<test>` of the gate-level run that the count names.")
    L.append("4. In the same registry row: the document, its issue, its address, the SHA-256 of the file that was read "
             "and the clause; the model named in the column `model` is a function or class in `test/`.")
    L.append("5. Optional, on a clone: `python flex/count.py --rtl <results.xml> --gl <gate-level results.xml ...>` "
             "prints the same table.")
    L.append("")
    if C["errors"]:
        L.append("**The count reported errors** (its job fails with them):\n")
        L += [f"- {e}" for e in C["errors"]]
        L.append("")
    else:
        L.append("The count reported no error: every program in `fw/` has one row, and no row claims more than its "
                 "evidence gives.\n")
    L.append("Conditions: all of these are results of logic simulation at 60 MHz with ideal pins (the RTL, and the "
             "gate-level netlist with functional cell models and no delays); no pad, cable, transceiver or silicon "
             "timing is in them ([Counting rule](counting.md) section 8).\n")
    with open(out_md, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"count page: strict {n}, broad {len(broad)}, families {len(fam)}, device interfaces {len(di)}, "
          f"after the tag {len(after)}, from {link(test)}")


if __name__ == "__main__":
    main(*sys.argv[1:])

"""Builds load images for the host program (CPython, on the PC). The board loads the result.

An image is a dict:
  name       program name
  clock_hz   the chip clock the image is built for; Chip.load refuses another clock (docs/host_port.md 11)
  equ        the .equ values set for that clock (empty if none)
  mem        [(address, words)] for WRITE_MEM: the program words, then any data-memory words
  cfg        [(address, words)] for WRITE_CFG: start addresses and RUN mask (0-4), pin words (16-30)

The USB device and the 10BASE-T station run only at 60 MHz: their helpers have the line rates fixed for that
clock (docs/helpers.md 1), so build() refuses them at any other clock.

Use: python host/build_image.py <name> <clock_hz> <out.py>   writes IMAGE = {...} as a module that
MicroPython can import.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "asm"))
sys.path.insert(0, os.path.join(ROOT, "fw"))
import pe_asm  # noqa: E402

PIN_OWN, PIN_OD, PIN_HDRV, PIN_HETH = 1 << 2, 1 << 3, 1 << 4, 1 << 5
HELPER_CLOCK_HZ = 60_000_000


def helper_pin(signal, eth):
    """Pin word: helper drive, helper select (0 USB, 1 10BASE-Te), signal (docs/host_port.md 4)."""
    return PIN_HDRV | (PIN_HETH if eth else 0) | (signal << 6)


def thread_pin(thread, open_drain=False):
    return PIN_OWN | (thread & 3) | (PIN_OD if open_drain else 0)


def assemble(path, equ=None):
    """Assembles path with the .equ lines of equ replaced; every name in equ must have an .equ line."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    for name, value in (equ or {}).items():
        pat = re.compile(r"^(\s*\.equ\s+%s\s*,)[^;\n]*" % re.escape(name), re.M | re.I)
        text, n = pat.subn(lambda m: "%s %d " % (m.group(1), value), text)
        if n != 1:
            raise ValueError("%s: .equ %s found %d times" % (path, name, n))
    return pe_asm.assemble(text, name=path)


def config(start=(0, 0, 0, 0), run=(1, 0, 0, 0), pins=None):
    head = [pc & 0x1FF for pc in start] + [sum(1 << n for n in range(4) if run[n])]
    p = list(pins or []) + [0] * (15 - len(pins or []))
    return [(0, head), (16, p)]


def build(name, clock_hz, equ=None, scale=1, seed=0xACE1):
    if name == "usb_dev":
        import usb_dev_data
        if clock_hz != HELPER_CLOCK_HZ:
            raise ValueError("usb_dev runs only at 60 MHz (USB helper line rate)")
        prog = assemble(os.path.join(ROOT, "fw", "usb_dev.s"))
        mem, _ = usb_dev_data.build(prog.symbols)
        pins = [helper_pin(0, False), helper_pin(1, False), helper_pin(5, False)]
    elif name == "eth_10bt":
        import eth_10bt_data
        if clock_hz != HELPER_CLOCK_HZ:
            raise ValueError("eth_10bt runs only at 60 MHz (10BASE-Te helper line rate)")
        prog = assemble(os.path.join(ROOT, "fw", "eth_10bt.s"))
        mem, _ = eth_10bt_data.build(prog.symbols, scale=scale, seed=seed)
        pins = [helper_pin(0, True), helper_pin(1, True), helper_pin(4, True)]
    else:
        raise ValueError("no recipe for %s" % name)
    v_first = prog.symbols["V_BASE"][0]
    assert prog.size <= v_first, "%s: %d program words overlap the variables at %d" % (name, prog.size, v_first)
    mem = [(0, prog.image()[:prog.size])] + [(a, list(w)) for a, w in mem]
    return {"name": name, "clock_hz": clock_hz, "equ": dict(equ or {}), "mem": mem, "cfg": config(pins=pins)}


def write_module(image, path):
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Generated by host/build_image.py; load with pe_host.core.Chip.load(IMAGE, clock_hz)\n")
        f.write("IMAGE = %r\n" % (image,))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        print(__doc__)
        sys.exit(2)
    write_module(build(sys.argv[1], int(sys.argv[2])), sys.argv[3])
